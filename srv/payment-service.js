import cds from '@sap/cds'
import { getDocumentRequirements, parseFormats, extensionOf, describeFileRules } from './lib/document-rules.js'
const LOG = cds.log('payment-request')

// Status codes (texts, colours and the 'editable' flag are in db/data/...-PaymentStatuses.csv)
const STATUS = {
  NEW: 'NEW', DOC_PENDING: 'DOC_PENDING', IN_APPROVAL: 'IN_APPROVAL', RETURN: 'RETURN',
  APPROVED: 'APPROVED', SENT_TO_BANK: 'SENT_TO_BANK', SETTLED: 'SETTLED',
  REJECTED: 'REJECTED', WF_ERROR: 'WF_ERROR'
}
// Upload rules for all files. The MIME type list is also enforced by an annotation in db/schema.cds.
// Formats and sizes per document type come from DocumentTypes.allowedFormats / maxSizeMB.
// The extension must match the MIME type ('decl.pdf' sent as Excel is rejected).
const MIME_BY_EXTENSION = {
  pdf:  'application/pdf',
  jpg:  'image/jpeg',
  png:  'image/png',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
}
const ALLOWED_MIME_TYPES = Object.values(MIME_BY_EXTENSION)
const MB = 1024 * 1024
const MAX_PACKAGE_BYTES  = 50 * MB   // total of all documents of one payment request
// Per-file size: DocumentTypes.maxSizeMB of the file's type. Files without a type (or of a type
// without a limit) may be as large as the largest maxSizeMB of all types, so a type's limit can be
// raised in the code list alone. The technical ceiling (@Validation.Maximum in db/schema.cds)
// equals the package limit, as no single file can exceed that anyway.

export default class PaymentRequestService extends cds.ApplicationService {
  init() {
    const { PaymentRequests, PaymentStatuses, DocumentTypes } = this.entities
    const Attachments = this.entities['PaymentRequests.attachments']   // generated by @cap-js/attachments
    // Attachment ID of a request: in req.data on create/patch, only in the URL keys on content upload
    const attachmentID = req => req.data.ID ?? req.params?.at(-1)?.ID

    /**
     * Reads a request's status and whether documents may still be changed in it.
     * The 'editable' flag comes from the PaymentStatuses code list.
     * @returns {{ code: string, name: string, editable: boolean } | undefined}
     */
    const statusOf = async ID => {
      const pr = await SELECT.one.from(PaymentRequests, ID).columns('status_code')
      if (!pr) return
      const st = await SELECT.one.from(PaymentStatuses, pr.status_code).columns('code', 'name', 'editable')
      return st ?? { code: pr.status_code, name: pr.status_code, editable: false }
    }

    // Header data comes from CPI — read-only in this API (attachments are separate entities)
    // this.before('UPDATE', PaymentRequests, req =>
    //   req.reject(405, 'Payment request data comes from CPI and cannot be changed'))
        /**
     * Edit (draft) is only allowed while the request is open.
     * Once the workflow is running, the document set is frozen.
     * Header fields are @readonly in the service, so in edit mode only attachments change.
     */
    this.before('EDIT', PaymentRequests, async req => {
      const ID = req.params[0]?.ID ?? req.params[0]
      const st = await statusOf(ID)
      if (st && !st.editable)
        req.reject(409, `Payment request cannot be edited in status '${st.name}'`)
    })

    // Re-check on Save: the workflow may have been started while the draft was open
    this.before('SAVE', PaymentRequests, async req => {
      const ID = req.data.ID ?? req.params[0]?.ID
      const st = await statusOf(ID)
      if (st && !st.editable)
        req.reject(409, `Changes cannot be saved in status '${st.name}'. Discard the draft.`)
    })

    /**
     * After Save: New <-> Document Pending follows the mandatory documents.
     * Return and Workflow Error stay as they are (the user restarts the workflow from there).
     */
    this.after('SAVE', PaymentRequests, async (_, req) => {
      const ID = req.data.ID ?? req.params[0]?.ID
      const pr = await SELECT.one.from(PaymentRequests, ID).columns('status_code')
      if (![STATUS.NEW, STATUS.DOC_PENDING].includes(pr?.status_code)) return
      const missing = await this.missingDocuments(ID)
      const status_code = missing.length ? STATUS.DOC_PENDING : STATUS.NEW
      if (status_code !== pr.status_code) await UPDATE(PaymentRequests, ID).with({ status_code })
    })

    /**
     * Attachments can only be added/changed/removed while the request is open.
     * Once the workflow is running, the document set is frozen.
     */
    this.before(['CREATE', 'UPDATE', 'DELETE'], Attachments, async req => {
      const parentID = req.data.up__ID ?? req.params?.[0]?.ID ?? req.params?.[0]
      const st = parentID && await statusOf(parentID)
      if (st && !st.editable)
        req.reject(409, `Attachments cannot be changed in status '${st.name}'`)
    })

        /**
     * File type whitelist: PDF, JPG, PNG, XLSX only.
     * Checks both the file extension and the MIME type, on create/rename and on content upload,
     * so neither 'invoice.exe' sent as PDF nor 'invoice.pdf' sent as an executable gets through.
     * The two must also match each other: 'decl.pdf' sent as an Excel file is rejected, otherwise
     * it would pass the per-type format check (which looks at the extension) for a PDF-only type.
     */
    this.before(['NEW', 'CREATE', 'UPDATE', 'PUT'], [Attachments, Attachments.drafts], async req => {
      const d = req.data
      const hasContent = 'content' in d
      // MIME type: from the request header on content upload, from the metadata otherwise
      const newMime = hasContent
        ? String(req.headers?.['content-type'] ?? '').split(';')[0].trim().toLowerCase() || undefined
        : d.mimeType?.toLowerCase()
      if (d.filename === undefined && newMime === undefined) return

      if (d.filename !== undefined) {
        const ext = extensionOf(d.filename)
        if (!MIME_BY_EXTENSION[ext])
          return req.reject(415, `File type '${ext ? '.' + ext : d.filename}' is not allowed. Allowed types: PDF, JPG, PNG, XLSX`)
      }
      if (newMime && !ALLOWED_MIME_TYPES.includes(newMime))
        return req.reject(415, `Content type '${newMime}' is not allowed. Allowed types: PDF, JPG, PNG, XLSX`)

      // Whichever of the two is not in this request comes from the stored attachment
      const ID = attachmentID(req)
      const current = (d.filename === undefined || !newMime) && ID
        ? await SELECT.one.from(req.target).columns('filename', 'mimeType').where({ ID })
        : undefined
      const filename = d.filename ?? current?.filename
      const mime = newMime ?? current?.mimeType?.toLowerCase()
      if (!filename || !mime) return
      const expected = MIME_BY_EXTENSION[extensionOf(filename)]
      if (expected && mime !== expected)
        return req.reject(415, `'${filename}' does not match its content type '${mime}' — the file extension must match the actual file format`)
    })

    /**
     * Package size limit: all documents of one payment request together ≤ 50 MB.
     * Runs when file content is uploaded; stores the size on the attachment.
     */
    this.before(['UPDATE', 'PUT'], [Attachments, Attachments.drafts], async req => {
      if (!('content' in req.data)) return                // metadata change only (doc type, note)
      const size = Number(req.headers?.['content-length'])
      if (!size) return req.reject(411, 'File size could not be determined (Content-Length missing)')

      const { total } = await SELECT.one.from(req.target)
        .columns('coalesce(sum(fileSize), 0) as total')
        .where({ up__ID: req.data.up__ID, ID: { '!=': attachmentID(req) } }) ?? { total: 0 }
      if (Number(total) + size > MAX_PACKAGE_BYTES)
        return req.reject(413, `Total size of all documents would be ${((Number(total) + size) / 1048576).toFixed(1)} MB — the limit is 50 MB per payment request`)

      req.data.fileSize = size
    })

    /**
     * Format and size per document type (customer checklist, e.g. Requestor Declaration: PDF, max 5 MB).
     * Users may upload first and pick the type afterwards, or the other way round, so this runs
     * on content upload, on rename and when the document type is set or changed.
     * Files without a type yet may be as large as the largest type limit (see MAX_PACKAGE_BYTES note).
     */
    this.before(['NEW', 'CREATE', 'UPDATE', 'PUT'], [Attachments, Attachments.drafts], async req => {
      const d = req.data
      const hasContent = 'content' in d
      if (!hasContent && d.docType_code === undefined && d.filename === undefined) return

      const ID = attachmentID(req)
      const current = ID && await SELECT.one.from(req.target)
        .columns('docType_code', 'filename', 'fileSize').where({ ID })
      const docType_code = d.docType_code !== undefined ? d.docType_code : current?.docType_code
      const type = docType_code && await SELECT.one.from(DocumentTypes, docType_code)
        .columns('name', 'allowedFormats', 'maxSizeMB')
      const filename = d.filename ?? current?.filename

      if (type && filename) {
        const formats = parseFormats(type.allowedFormats)
        if (formats.length && !formats.includes(extensionOf(filename)))
          return req.reject(415, `'${type.name}' accepts ${describeFileRules({ allowedFormats: type.allowedFormats })} only — '${filename}' cannot be used for this document type`)
      }

      const size = hasContent ? Number(req.headers?.['content-length']) : current?.fileSize
      if (!size) return
      if (type?.maxSizeMB) {
        if (size > type.maxSizeMB * MB)
          return req.reject(413, `'${type.name}' may be at most ${type.maxSizeMB} MB — '${filename ?? 'this file'}' is ${(size / MB).toFixed(1)} MB`)
      } else if (hasContent) {
        // No type (yet), or a type without its own limit: largest limit of all document types
        const { maxMB } = await SELECT.one.from(DocumentTypes).columns('max(maxSizeMB) as maxMB') ?? {}
        if (maxMB && size > maxMB * MB)
          return req.reject(413, `A document may be at most ${maxMB} MB — '${filename ?? 'this file'}' is ${(size / MB).toFixed(1)} MB`)
      }
    })

       /**
     * Document checklist for one payment request, driven by the requirement matrix
     * (company code + payment type). Reads the draft attachments while the request is
     * being edited, otherwise the saved ones.
     */
    this.on('READ', 'DocumentChecklist', async req => {
      const parent = req.params?.[0] ?? {}
      const requestID = parent.ID ?? parent
      if (!requestID || typeof requestID !== 'string') return []
      const fromDraft = parent.IsActiveEntity === false

      const pr = await SELECT.one.from(PaymentRequests, requestID).columns('companyCode', 'paymentType_code')
      if (!pr) return []
      const { rules } = await getDocumentRequirements(pr)
      const files = await SELECT.from(fromDraft ? Attachments.drafts : Attachments)
        .columns('docType_code', 'filename').where({ up__ID: requestID }).orderBy('createdAt')

      return rules.map(r => {
        // all files of this type, in upload order (several are allowed, e.g. two supporting documents)
        const names = files.filter(f => f.docType_code === r.docType_code).map(f => f.filename)
        const file = names.length > 0
        const status = file ? 'Uploaded'
          : r.blocking ? 'Pending'
          : r.level_code === 'CONDITIONAL' ? 'If applicable' : 'Optional'
        return {
          request_ID: requestID, docType_code: r.docType_code, docTypeName: r.docTypeName,
          fileRules: r.fileRules,
          level: r.levelName, conditionNote: r.conditionNote, sortOrder: r.sortOrder,
          status, criticality: file ? 3 : r.blocking ? 2 : 0,
          fileName: file ? names.join(', ') : null
        }
      })
    })

    /**
     * Bound action: start the BPA workflow for one payment request.
     * 1. Request must be in an open status
     * 2. All mandatory document types must be attached
     * 3. Call BPA, store instance ID, set status
     */
    // In edit mode the action targets the draft — the workflow only runs on the saved request
    this.on('startWorkflow', PaymentRequests.drafts, req =>
      req.error(409, 'Save or discard your changes before starting the workflow'))

    this.on('startWorkflow', PaymentRequests, async req => {
      const ID = req.params[0]?.ID ?? req.params[0]
      const st = await statusOf(ID)
      if (!st) return req.error(404, 'Payment request not found')
      if (!st.editable)
        return req.error(409, `Workflow cannot be started in status '${st.name}'`)

      // Mandatory documents check (requirement matrix: company code + payment type)
      const missing = await this.missingDocuments(ID)
      const pr = await SELECT.one.from(PaymentRequests, ID).columns('companyCode', 'paymentType_code')
      const { configured } = await getDocumentRequirements(pr)
      if (!configured)
        return req.error(400, `No document requirements are configured for company ${pr.companyCode} and payment type ${pr.paymentType_code ?? '(none)'}. Please contact the administrator.`)
      if (missing.length)
        return req.error(400, `Mandatory documents missing: ${missing.map(m => m.name).join(', ')}. Upload them before starting the workflow.`)

      const wf = await this.callBPA(ID)
      if (wf.status_code === STATUS.WF_ERROR) return req.error(502, `BPA workflow start failed: ${wf.workflowMessage}`)
      return SELECT.one.from(PaymentRequests, ID)
    })

    return super.init()
  }

    /**
   * Mandatory (blocking) documents that are not yet attached to the saved payment request.
   * Conditional and optional documents never block.
   * @param {string} ID payment request ID
   * @returns {Promise<Array<{ code: string, name: string }>>}
   */
  async missingDocuments(ID) {
    const { PaymentRequests } = this.entities
    const Attachments = this.entities['PaymentRequests.attachments']
    const pr = await SELECT.one.from(PaymentRequests, ID).columns('companyCode', 'paymentType_code')
    const { rules } = await getDocumentRequirements(pr ?? {})
    const attached = await SELECT.from(Attachments).columns('docType_code').where({ up__ID: ID })
    const have = new Set(attached.map(a => a.docType_code))
    return rules.filter(r => r.blocking && !have.has(r.docType_code))
                .map(r => ({ code: r.docType_code, name: r.docTypeName }))
  }

  /**
   * Builds the BPA payload and starts the workflow instance.
   * No attachments are sent to BPA; approvers view documents through CAP
   * (IntegrationService.getAttachedDocuments).
   */
  async callBPA(ID) {
    const { PaymentRequests } = this.entities
    const pr = await SELECT.one.from(PaymentRequests, ID)

    // Field names must match the input of the BPA process trigger exactly
    // (process ap10.abhit-playground.paymentapproval.paymentApproval)
    const payload = {
      definitionId: cds.env.requires.bpa.definitionId,
      context: {
        bTP_PRN_ID:     pr.btpPaymentRef,
        kldrequestid:   pr.requestId,
        vendorcode:     pr.vendorCode,
        vendorname:     pr.vendorName,
        paymentamount:  Number(pr.paymentAmount),
        currency:       pr.currency_code,
        paymentduedate: pr.paymentDueDate,
        companycode:    pr.companyCode,
        costcentre:     pr.costCentre,
        glaccount:      pr.glAccount,
        paymentmethod:  pr.paymentMethod_code,
        bankname:       pr.bankName,
        iban:           pr.iban,
        bankaccountno:  pr.bankAccountNo,
        swiftcode:      pr.swiftCode,
        requestorname:  pr.requestorName,
        requestorempid: pr.requestorEmpId,
        kldcreatedat:   pr.requestCreatedAt,
        status:         STATUS.IN_APPROVAL
      }
    }

    let wf
    try {
      // 'bpa' = mock locally (server.js), BTP destination in production
      const bpa = await cds.connect.to('bpa')
      const result = await bpa.send({ method: 'POST', path: '/workflow/rest/v1/workflow-instances', data: payload })
      wf = { status_code: STATUS.IN_APPROVAL, bpaWorkflowInstanceId: result.id, workflowMessage: null }
      LOG.info(`BPA workflow ${result.id} started for ${pr.btpPaymentRef}`)
    } catch (err) {
      const msg = (err.reason?.response?.data?.error?.message || err.message || 'Unknown error').slice(0, 500)
      wf = { status_code: STATUS.WF_ERROR, bpaWorkflowInstanceId: null, workflowMessage: msg }
      LOG.error(`BPA workflow start failed for ${pr.btpPaymentRef}: ${msg}`)
    }
    await UPDATE(PaymentRequests, ID).with(wf)
    return wf
  }
}